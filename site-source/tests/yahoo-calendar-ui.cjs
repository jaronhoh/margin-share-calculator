const {chromium}=require('/Users/jaron/.cache/codex-runtimes/codex-primary-runtime/dependencies/node/node_modules/playwright');
const A=require('node:assert/strict');

(async()=>{
  const browser=await chromium.launch({headless:true,executablePath:'/Users/jaron/Library/Caches/ms-playwright/chromium_headless_shell-1248/chrome-headless-shell-mac-arm64/chrome-headless-shell'});
  const page=await browser.newPage(),errors=[];
  page.on('pageerror',e=>errors.push(e.message));
  await page.addInitScript(()=>{window.confirm=()=>true;const RealDate=Date;window.Date=class extends RealDate{constructor(...args){super(...(args.length?args:['2025-02-08T12:00:00Z']));}static now(){return new RealDate('2025-02-08T12:00:00Z').getTime();}};});
  await page.route('**/api/yahoo-chart?**',async route=>{
    const url=new URL(route.request().url()),ticker=url.searchParams.get('ticker');
    const dates=ticker==='^KLSE'?['2025-02-04','2025-02-07']:['2025-02-04','2025-02-07'];
    const closes=ticker==='^KLSE'?[1600,1610]:[6.3,6.4];
    const timestamp=dates.map(d=>Math.floor(Date.parse(`${d}T04:00:00Z`)/1000));
    return route.fulfill({status:200,contentType:'application/json',body:JSON.stringify({chart:{result:[{meta:{symbol:ticker,currency:'MYR',exchangeTimezoneName:'Asia/Kuala_Lumpur'},timestamp,indicators:{quote:[{close:closes}]}}],error:null}})});
  });
  await page.goto(process.env.TEST_URL||'http://127.0.0.1:8765');
  await page.locator('#rows tr').first().waitFor();
  await page.locator('#openSettings').click();
  await page.locator('#stockCode').fill('1066.KL');
  await page.locator('#startDate').fill('2025-02-04');
  await page.locator('#endDate').fill('2025-02-07');
  await page.locator('#fetchYahoo').click();
  await page.waitForFunction(()=>!document.querySelector('#marketUpdateStatus').textContent.includes('正在连接'));
  A.equal(await page.locator('#marketUpdateStatus').textContent().then(t=>t.includes('新增')||t.includes('相同')||t.includes('冲突')),true,await page.locator('#marketUpdateError').textContent());
  A.match(await page.locator('#marketUpdateSource').textContent(),/\^KLSE 基准推定休市日/);
  A.equal(await page.locator('#marketUpdateRows tr').count(),5);
  await page.locator('#buildMarketCandidate').click();
  A.equal(await page.locator('#applyMarketCandidate').isDisabled(),false,await page.locator('#marketUpdateError').textContent());
  await page.locator('#applyMarketCandidate').click();
  await page.waitForFunction(()=>document.querySelector('#marketUpdateStatus').textContent==='已保存并应用'||document.querySelector('#marketUpdateError').textContent.length>0);
  A.equal(await page.locator('#marketUpdateStatus').textContent(),'已保存并应用',await page.locator('#marketUpdateError').textContent());
  A.equal(await page.locator('#resultStatus').textContent(),'1066.KL 收盘价回测完成');
  A.match(await page.locator('#rowsCount').textContent(),/2 个交易日/);
  A.equal(await page.locator('#rows tr[data-date="2025-02-05"]').count(),0);
  A.equal(await page.locator('#rows tr[data-date="2025-02-06"]').count(),0);
  A.equal(await page.locator('#rows tr[data-date="2025-02-04"]').count(),1);
  A.equal(await page.locator('#rows tr[data-date="2025-02-07"]').count(),1);
  const [download]=await Promise.all([page.waitForEvent('download'),page.locator('#export').click()]);
  const path=await download.path(),fs=require('node:fs'),snapshot=JSON.parse(fs.readFileSync(path,'utf8'));
  A.equal(snapshot.marketDataSource.marketCalendar.sourceTicker,'^KLSE');
  A.deepEqual(snapshot.marketDataSource.marketCalendar.closedDates,['2025-02-05','2025-02-06']);
  A.equal(snapshot.marketData.rows.find(x=>x.date==='2025-02-05').reason,'yahoo-market-holiday');
  A.equal(snapshot.marketData.rows.find(x=>x.date==='2025-02-06').carryForwardFrom,'2025-02-04');
  A(Number((await page.locator('#summary .metric').nth(9).locator('strong').textContent()).replace(/[^0-9.]/g,''))>0);
  await page.reload();
  await page.locator('#rows tr').first().waitFor();
  A.match(await page.locator('#rowsCount').textContent(),/2 个交易日/);
  A.equal(await page.locator('#rows tr[data-date="2025-02-05"]').count(),0);
  A.equal(await page.locator('#rows tr[data-date="2025-02-06"]').count(),0);
  A(Number((await page.locator('#summary .metric').nth(9).locator('strong').textContent()).replace(/[^0-9.]/g,''))>0);
  A.deepEqual(errors,[]);
  console.log('PASS UI Yahoo ^KLSE calendar import, candidate save/restore validation, closed-day ledger filtering, source provenance, and calendar-day interest');
  await browser.close();
})().catch(error=>{console.error(error);process.exit(1);});
