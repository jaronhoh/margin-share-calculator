import assert from 'node:assert/strict';
import {defaultDividends,defaultPaymentDateApprovals,mergeDefaultPaymentDateApprovals,normalizeDividend,validateDividends} from '../dist/dividend-events.mjs';
import {runBacktest} from '../dist/engine.mjs';
assert.deepEqual(defaultDividends(),[]);
assert.deepEqual(defaultPaymentDateApprovals(),[]);
const imported=[{date:'2026-03-26',perShare:.33,source:'user-dividend-csv-confirmed',paymentDate:'2026-03-26',exDate:'2026-03-12'}];
assert.deepEqual(mergeDefaultPaymentDateApprovals(imported,[],'1155.KL'),[]);
assert.deepEqual(mergeDefaultPaymentDateApprovals(imported,[],'1066.KL'),[]);
assert.deepEqual(normalizeDividend(imported[0]),{...imported[0],dateType:'unverified-payment-date'});
assert.equal(normalizeDividend({date:'2026-03-26',perShare:.33}).source,'manual');
validateDividends(imported);
assert.throws(()=>validateDividends([{date:'2026-02-30',perShare:.3}]));
const market=[{date:'2026-03-25',price:10,dividendPerShare:0},{date:'2026-03-26',price:10,dividendPerShare:0}];
const config={ownShares:2000,financedShares:18000,startPrice:10,annualRate:0,targetLsr:.6,refinanceTrigger:0,marginCallLsr:.99,forceSellLsr:null,callStrategy:'cash',safeGap:.001,feeRate:0,lotSize:100};
const noDividends=runBacktest(config,market);
assert.equal(noDividends.summary.cumulativeDividend,0);
const userDividend=runBacktest(config,market.map((row,i)=>({...row,dividendPerShare:i?.33:0})));
assert.ok(userDividend.summary.cumulativeDividend>0);
console.log('PASS no bundled Excel dividends, no Maybank payment defaults, manual import, validation and zero-dividend backtest');
